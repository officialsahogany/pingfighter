    def compose_journey_ahead(self, skill: float, dash: float, item: float, guard: float) -> str:
        """앞으로의 여정을 유머러스하게 제시"""
        
        scores = {"skill": skill, "dash": dash, "item": item, "guard": guard}
        weakest = min(scores, key=scores.get)
        strongest = max(scores, key=scores.get)
        
        tips = []
        
        # 가장 약한 부분에 대한 조언
        weak_advice = {
            "skill": "스킬 버튼과 친해지세요. 커피 한잔 사주면서 대화를 시작해보는 건 어때요?",
            "dash": "대쉬는 마라톤이 아니라 단거리 달리기입니다. 100m 달리기 선수처럼 폭발적으로!",
            "item": "아이템은 포켓몬입니다. 다 모아보세요! '너로 정했다!'를 외치며 사용하면 효과 2배!",
            "guard": "가드는 마음의 벽이 아니라 패들의 벽입니다. 마음을 열고 공을 맞이하세요!"
        }
        
        tips.append(f"💡 【최우선 과제】 {weak_advice[weakest]}")
        
        # 가장 강한 부분 칭찬
        strong_praise = {
            "skill": "당신의 스킬 실력은 이미 예술의 경지! 이제 유튜브 채널을 열어보는 건 어때요?",
            "dash": "당신의 대쉬는 소닉도 부럽워할 수준! 속도위반 딱지 조심하세요!",
            "item": "아이템 마스터님! 이제 아이템이 당신을 선택합니다!",
            "guard": "철벽 수비! 당신을 뚫으려면 드릴이 필요할 것 같네요!"
        }
        
        tips.append(f"🌟 【자랑거리】 {strong_praise[strongest]}")
        
        # 전체적인 조언
        avg = (skill + dash + item + guard) / 4
        if avg >= 70:
            tips.append("🎮 【총평】 거의 다 왔습니다! 조금만 더 하면 전설이 됩니다. 그런데 전설이 되면 심심할 수도...")
        elif avg >= 50:
            tips.append("🎮 【총평】 성장이 눈에 보입니다! 이 속도면 다음 달엔 프로게이머 데뷔?")
        else:
            tips.append("🎮 【총평】 모든 시작은 아름답습니다! 실력은 없어도 열정은 S급!")
        
        # 재미있는 목표 제시
        fun_goals = [
            "🎯 오늘의 미션: 대쉬로 3번 연속 공 받기 (실패하면 벌칙: 팔굽혀펴기 1개)",
            "🎯 도전 과제: 아이템 없이 한 라운드 이기기 (상금: 자존감 +100)",
            "🎯 숨겨진 퀘스트: 완벽한 타이밍으로 10번 치기 (보상: 손목 통증)",
            "🎯 특별 임무: 보스를 3-0으로 이기기 (달성 시 보스가 울 수도 있음)",
            "🎯 비밀 미션: 가드만으로 1분 버티기 (클리어 시 '철벽 인증서' 획득)"
        ]
        
        tips.append(random.choice(fun_goals))
        
        return "\n".join(tips)